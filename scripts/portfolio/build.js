#!/usr/bin/env node
// Rebuild the reviewed portfolio from the local source folder. Full-size WebP
// is lossless; smaller previews are only used in the gallery and index.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const sharp = require('sharp');

const root = path.resolve(__dirname, '../..');
const sourceDir = path.join(root, 'portfolio assets');
const outputDir = path.join(root, 'images/portfolio');
const catalog = require('./catalog.json');
const excludedSources = new Set(['Consumer/Consumer.006.jpeg']);
const reuseImages = process.argv.includes('--reuse-images');
const publishedCatalog = catalog.filter(p => p.published !== false);
const labels = {
  all: { en: 'All', zh: '全部' },
  'brand-imc': { en: 'Brand IMC', zh: '品牌整合营销' },
  product: { en: 'Product', zh: '产品' },
  digital: { en: 'Digital', zh: '数字体验' },
  design: { en: 'Design', zh: '设计' },
  consumer: { en: 'Consumer', zh: '消费者连接' }
};

async function build() {
  fs.mkdirSync(outputDir, { recursive: true });
  const supplied = fs.readdirSync(sourceDir).filter(f => !f.startsWith('.'))
    .flatMap(folder => fs.readdirSync(path.join(sourceDir, folder))
      .filter(f => /\.(jpe?g|png)$/i.test(f)).map(f => folder + '/' + f))
    .filter(source => !excludedSources.has(source)).sort();
  assert.deepEqual(catalog.map(p => p.source).sort(), supplied, 'Every source image must appear exactly once');
  assert.equal(new Set(catalog.map(p => p.id)).size, catalog.length);
  catalog.forEach(p => {
    assert(p.published === undefined || typeof p.published === 'boolean', 'Invalid publication flag: ' + p.id);
    if (p.published === false) {
      // Keep the source/catalog for a future restore, but remove public assets.
      for (const suffix of ['.webp', '-preview.webp']) {
        fs.rmSync(path.join(outputDir, p.id + suffix), { force: true });
      }
    }
  });
  const projects = [], manifest = {}, report = [];
  let next = 0;
  async function processImage(index) {
    const p = publishedCatalog[index];
    assert(p.name && p.brand && labels[p.cat]);
    const input = path.join(sourceDir, p.source);
    const fullPath = path.join(outputDir, p.id + '.webp');
    const previewPath = path.join(outputDir, p.id + '-preview.webp');
    const meta = await sharp(input).metadata();
    if (!reuseImages || !fs.existsSync(fullPath) || !fs.existsSync(previewPath)) {
      await sharp(input).keepIccProfile().webp({ lossless: true, quality: 100, effort: 6 }).toFile(fullPath);
      await sharp(input).keepIccProfile().resize({ width: 1000, withoutEnlargement: true })
        .webp({ quality: 92, effort: 6, smartSubsample: true }).toFile(previewPath);
    }
    // Compare decoded pixels in the same sRGB space, not compressed bytes.
    const before = await sharp(input).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const after = await sharp(fullPath).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    assert.deepEqual(after.info, before.info, p.source + ': dimensions/channels changed');
    assert(before.data.equals(after.data), p.source + ': full-resolution pixels changed');
    const blur = await sharp(input).resize(20).jpeg({ quality: 40 }).toBuffer();
    const full = 'images/portfolio/' + p.id + '.webp';
    projects[index] = { name: p.name, brand: p.brand, cat: p.cat, img: full };
    manifest[p.id] = {
      webp: 'images/portfolio/' + p.id + '-preview.webp',
      full, blur: 'data:image/jpeg;base64,' + blur.toString('base64'),
      width: meta.width, height: meta.height
    };
    report[index] = { source: p.source, name: p.name, brand: p.brand, category: p.cat,
      width: meta.width, height: meta.height, sourceBytes: fs.statSync(input).size,
      fullBytes: fs.statSync(fullPath).size, previewBytes: fs.statSync(previewPath).size,
      losslessPixelMatch: true, metadataSource: p.metadataSource };
    console.log('Verified lossless: ' + p.id);
  }
  // Bound memory/CPU use while keeping the reviewed source order stable.
  await Promise.all(Array.from({ length: 4 }, async () => {
    while (next < publishedCatalog.length) await processImage(next++);
  }));
  const orderedManifest = Object.fromEntries(publishedCatalog.map(p => [p.id, manifest[p.id]]));
  const declarations = { FILTER_LABELS: labels, FILTER_SHORT: labels, PROJECTS: projects, IMAGE_MANIFEST: orderedManifest };
  fs.writeFileSync(path.join(__dirname, 'data.js'),
    '// Generated by scripts/portfolio/build.js from the reviewed source catalog.\n' +
    Object.entries(declarations).map(([name, data]) => 'const ' + name + ' = ' + JSON.stringify(data, null, 2) + ';').join('\n\n') + '\n');
  fs.writeFileSync(path.join(root, 'docs/portfolio-conversion-report.json'), JSON.stringify(report, null, 2) + '\n');
  const totals = report.reduce((sum, p) => ({ source: sum.source + p.sourceBytes,
    full: sum.full + p.fullBytes, preview: sum.preview + p.previewBytes }), { source: 0, full: 0, preview: 0 });
  console.log(JSON.stringify({ works: projects.length, totals, fullSavedPercent: (100 * (1 - totals.full / totals.source)).toFixed(1) }));
}

build().catch(error => { console.error(error); process.exitCode = 1; });
